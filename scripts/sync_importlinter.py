#!/usr/bin/env python3
"""Regenerate backend/.importlinter from the modules that actually exist in backend/app/modules/.

`make importlinter` (and /new-module) writes it; `make lint` runs it with --check (fails on drift), so contracts never list a module that doesn't exist
yet (import-linter fails on missing modules) and never forget a new one.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODULES_DIR = ROOT / "backend/app/modules"
OUT = ROOT / "backend/.importlinter"
AI_MODULE = "ai"

if not MODULES_DIR.exists():  # no backend yet: nothing to generate or check
    print("importlinter: backend/app/modules not created yet — skipped")
    sys.exit(0)

modules = sorted(p.name for p in MODULES_DIR.iterdir() if p.is_dir() and (p / "__init__.py").exists())


def block(names: list[str]) -> str:
    return "\n".join(f"    app.modules.{m}" for m in names)


parts = [
    "# GENERATED by scripts/sync_importlinter.py from backend/app/modules/ — do not edit by hand.",
    "[importlinter]",
    "root_package = app",
    "include_external_packages = True",
    "",
    "# core/ and shared/ are infrastructure: they must never import business modules",
    "[importlinter:contract:core-no-modules]",
    "name = core and shared don't depend on modules",
    "type = forbidden",
    "source_modules =",
    "    app.core",
    "    app.shared",
    "forbidden_modules =",
    "    app.modules",
]
if len(modules) >= 2:
    parts += [
        "",
        "# Modules may depend on each other ONLY through app.modules.<x>.public",
        "[importlinter:contract:module-independence]",
        "name = Backend modules are independent: only public facades, tests may also use testing factories",
        "type = independence",
        "unmatched_ignore_imports_alerting = none",
        "modules =",
        block(modules),
        "ignore_imports =",
        "    app.modules.** -> app.modules.*.public",
        "    app.modules.*.tests.** -> app.modules.*.testing",
    ]
if modules:
    parts += [
        "",
        "# Inside every module: upper layers may import lower ones, never the reverse.",
        "# (x) = optional layer; a | b = siblings that must not import each other.",
        "[importlinter:contract:module-layers]",
        "name = Module internal layers: routers/handlers/jobs, public, services, providers, schemas/repositories, models, domain",
        "type = layers",
        "containers =",
        block(modules),
        "layers =",
        "    (testing)",
        "    (routers) | (handlers) | (jobs)",
        "    (public)",
        "    (services)",
        "    (providers)",
        "    (schemas) | (repositories)",
        "    (models)",
        "    (domain)",
    ]
    parts += [
        "",
        "# Adapters speak an external protocol; business data goes through the module's services/ledger.",
        "[importlinter:contract:providers-no-data-access]",
        "name = Providers never touch repositories or models",
        "type = forbidden",
        "source_modules =",
        "    app.modules.*.providers",
        "forbidden_modules =",
        "    app.modules.*.repositories",
        "    app.modules.*.models",
        "allow_indirect_imports = True",
        "",
        "# Routes are thin: they call services, never the database layer.",
        "[importlinter:contract:routers-no-data-access]",
        "name = Routers never touch repositories, models or SQLAlchemy",
        "type = forbidden",
        "source_modules =",
        "    app.modules.*.routers",
        "forbidden_modules =",
        "    app.modules.*.repositories",
        "    app.modules.*.models",
        "    sqlalchemy",
        "allow_indirect_imports = True",
    ]
non_ai = [m for m in modules if m != AI_MODULE]
if non_ai:
    parts += [
        "",
        "# Only the ai module may talk to Anthropic",
        "[importlinter:contract:anthropic-only-in-ai]",
        "name = Only modules.ai imports anthropic",
        "type = forbidden",
        "source_modules =",
        block(non_ai),
        "forbidden_modules =",
        "    anthropic",
    ]

content = "\n".join(parts) + "\n"
if "--check" in sys.argv:  # used by `make lint` / CI: never rewrites, fails on drift
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if current != content:
        print("importlinter: backend/.importlinter is out of date — run `make importlinter` and commit it")
        sys.exit(1)
    print(f"importlinter: contracts up to date ({len(modules)} module(s))")
    sys.exit(0)
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(content, encoding="utf-8")
print(f"importlinter: {len(modules)} module(s) → {OUT.relative_to(ROOT)}")
